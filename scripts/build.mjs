#!/usr/bin/env node
// npm run build — produces everything that ships, in this order:
//
//   1. clean dist/ and the generated legacy stub directories
//   2. tsup: dist/index.js (ESM) and dist/index.cjs (CJS, module.exports = CryptoJS)
//   3. declarations: dist/types.d.{ts,cts} (src/compat/types.ts verbatim) and
//      dist/modern.d.{ts,cts} (src/modern bundled by rollup-plugin-dts)
//   4. generated entry points from scripts/subpaths.mjs: dist/index.d.{ts,cts}, one ESM/CJS shim
//      pair per crypto-js module path, and <name>/package.json stubs for legacy resolvers
//   5. package.json "exports" and "files", rewritten only when they differ
//   6. a type-check of every generated declaration file (skipLibCheck off)
//
// Usage: node scripts/build.mjs
// Re-runnable: every step overwrites its outputs; nothing outside dist/, the stub directories and
// the two package.json fields is touched.
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT_ALIAS, SUBPATHS } from './subpaths.mjs';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const rel = (p) => path.relative(ROOT, p) || '.';

const GENERATED = '// Generated by scripts/build.mjs. Do not edit.\n';

function log(message) {
  process.stdout.write(`[build] ${message}\n`);
}

function fail(message) {
  process.stderr.write(`[build] ERROR: ${message}\n`);
  process.exit(1);
}

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

/** Path of a subpath's legacy stub directory (package root, e.g. ./sha256/package.json). */
function stubDir(name) {
  return path.join(ROOT, name);
}

/** The exact content of a legacy stub, so cleaning can prove it only removes what it wrote. */
export function stubContent(name) {
  return `${JSON.stringify(
    {
      main: `../dist/${name}.cjs`,
      types: `../dist/${name}.d.cts`,
      sideEffects: false,
    },
    null,
    2,
  )}\n`;
}

// ---------------------------------------------------------------------------------------------
// 1. clean
// ---------------------------------------------------------------------------------------------
function clean() {
  // Validate before deleting anything, so a refusal leaves the previous build intact.
  const stubs = SUBPATHS.map(({ name }) => ({ name, dir: stubDir(name) })).filter(({ dir }) => fs.existsSync(dir));
  for (const { name, dir } of stubs) {
    const entries = fs.readdirSync(dir);
    const stub = path.join(dir, 'package.json');
    const isOurStub =
      entries.length === 1 && entries[0] === 'package.json' && fs.readFileSync(stub, 'utf8') === stubContent(name);
    if (!isOurStub) {
      fail(`${rel(dir)}/ exists but is not a generated legacy stub; refusing to delete it.`);
    }
  }
  fs.rmSync(DIST, { recursive: true, force: true });
  for (const { dir } of stubs) fs.rmSync(dir, { recursive: true });
}

// ---------------------------------------------------------------------------------------------
// 2. JavaScript (tsup)
// ---------------------------------------------------------------------------------------------
function buildJs() {
  const cli = require.resolve('tsup/dist/cli-default.js');
  const result = spawnSync(process.execPath, [cli], { cwd: ROOT, stdio: 'inherit' });
  if (result.status !== 0) fail(`tsup exited with status ${result.status ?? result.signal}`);
  for (const file of ['index.js', 'index.cjs']) {
    if (!fs.existsSync(path.join(DIST, file))) fail(`tsup did not produce dist/${file}`);
  }
  const cjs = fs.readFileSync(path.join(DIST, 'index.cjs'), 'utf8');
  if (!/^module\.exports = /m.test(cjs)) {
    fail('dist/index.cjs does not assign module.exports');
  }
  for (const file of ['index.js', 'index.cjs']) {
    const references = moduleReferences(path.join(DIST, file));
    if (references.length > 0) fail(`dist/${file} still loads modules at runtime: ${references.join(', ')}`);
  }
}

/**
 * Every module specifier a JS or declaration file references (imports, re-exports, require(),
 * import(), import types, triple-slash references), read from the AST so that code samples in
 * comments are ignored.
 */
export function moduleReferences(file) {
  const ts = require('@typescript/typescript6');
  const text = fs.readFileSync(file, 'utf8');
  const kind = /\.d\.c?ts$/.test(file) ? ts.ScriptKind.TS : ts.ScriptKind.JS;
  const sourceFile = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, kind);
  const found = [
    ...sourceFile.referencedFiles.map((r) => r.fileName),
    ...sourceFile.typeReferenceDirectives.map((r) => r.fileName),
  ];
  const visit = (node) => {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier) {
      found.push(node.moduleSpecifier.text);
    } else if (ts.isImportEqualsDeclaration(node) && ts.isExternalModuleReference(node.moduleReference)) {
      found.push(node.moduleReference.expression.text);
    } else if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument)) {
      found.push(node.argument.literal.text);
    } else if (
      ts.isCallExpression(node) &&
      (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
        (ts.isIdentifier(node.expression) && node.expression.text === 'require')) &&
      node.arguments.length > 0
    ) {
      const [argument] = node.arguments;
      found.push(ts.isStringLiteralLike(argument) ? argument.text : `<dynamic: ${argument.getText()}>`);
    }
    ts.forEachChild(node, visit);
  };
  visit(sourceFile);
  return [...new Set(found)];
}

// ---------------------------------------------------------------------------------------------
// 3. declarations
// ---------------------------------------------------------------------------------------------
function copyCompatTypes() {
  const ts = require('@typescript/typescript6');
  const file = path.join(ROOT, 'src/compat/types.ts');
  const source = fs.readFileSync(file, 'utf8');
  // Shipped verbatim as a declaration file, so: no imports/re-exports, and only statements that
  // are valid at the top level of a .d.ts (interfaces, type aliases, `declare`d declarations).
  const sourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.ES2020, true, ts.ScriptKind.TS);
  for (const statement of sourceFile.statements) {
    const declared = ts.getCombinedModifierFlags(statement) & ts.ModifierFlags.Ambient;
    const ok =
      ts.isInterfaceDeclaration(statement) ||
      ts.isTypeAliasDeclaration(statement) ||
      ((ts.isModuleDeclaration(statement) || ts.isVariableStatement(statement) || ts.isFunctionDeclaration(statement) || ts.isClassDeclaration(statement)) && declared);
    if (!ok) {
      const { line } = sourceFile.getLineAndCharacterOfPosition(statement.getStart());
      fail(`src/compat/types.ts:${line + 1} is not declaration-only (${ts.SyntaxKind[statement.kind]}); it is shipped verbatim as dist/types.d.ts`);
    }
  }
  write(path.join(DIST, 'types.d.ts'), source);
  write(path.join(DIST, 'types.d.cts'), source);
}

async function bundleModernTypes() {
  const { rollup } = await import('rollup');
  const { dts } = await import('rollup-plugin-dts');
  const bundle = await rollup({
    input: path.join(ROOT, 'src/modern/index.ts'),
    plugins: [dts({ tsconfig: path.join(ROOT, 'tsconfig.json'), compilerOptions: { noEmit: false } })],
    onwarn(warning) {
      fail(`rollup-plugin-dts: ${warning.message}`);
    },
  });
  const { output } = await bundle.generate({ format: 'es' });
  await bundle.close();
  if (output.length !== 1) fail(`expected one declaration chunk for src/modern, got ${output.length}`);
  const code = output[0].code;
  write(path.join(DIST, 'modern.d.ts'), code);
  write(path.join(DIST, 'modern.d.cts'), code);
  const references = moduleReferences(path.join(DIST, 'modern.d.ts'));
  if (references.length > 0) {
    fail(`dist/modern.d.ts must be self-contained but references: ${references.join(', ')}`);
  }
}

// ---------------------------------------------------------------------------------------------
// 4. generated entry points
// ---------------------------------------------------------------------------------------------

/** Exported names of the compat namespace and of the modern API, read with the TS compiler API. */
export function readExportNames() {
  const ts = require('@typescript/typescript6');
  const files = [path.join(DIST, 'types.d.ts'), path.join(DIST, 'modern.d.ts')];
  const program = ts.createProgram(files, { noEmit: true, types: [], lib: ['lib.es2020.d.ts'], strict: true });
  const checker = program.getTypeChecker();
  const exportsOf = (file) => {
    const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(file));
    if (!moduleSymbol) fail(`${rel(file)} is not a module`);
    return checker.getExportsOfModule(moduleSymbol);
  };
  const namespace = exportsOf(files[0]).find((s) => s.name === 'CryptoJS');
  if (!namespace) fail('dist/types.d.ts does not export namespace CryptoJS');
  const compat = checker.getExportsOfModule(namespace).map((s) => s.name);
  const modern = exportsOf(files[1]).map((s) => {
    const target = s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s;
    const typeOnly = Boolean(checker.getTypeOnlyAliasDeclaration?.(s)) || !(target.flags & ts.SymbolFlags.Value);
    const declaration = target.declarations?.[0];
    const typeParameters =
      declaration && 'typeParameters' in declaration && declaration.typeParameters
        ? declaration.typeParameters.map((p) => p.name.text)
        : [];
    return { name: s.name, typeOnly, typeParameters };
  });
  const clash = modern.filter((m) => compat.includes(m.name)).map((m) => m.name);
  if (clash.length > 0) fail(`modern API names collide with crypto-js names: ${clash.join(', ')}`);
  return { compat, modern };
}

function namespaceBody(compat, modern) {
  const lines = compat.map((name) => `    export import ${name} = _C.${name};`);
  for (const { name, typeOnly, typeParameters } of modern) {
    if (!typeOnly) {
      lines.push(`    export import ${name} = _M.${name};`);
    } else if (typeParameters.length === 0) {
      lines.push(`    export type ${name} = _M.${name};`);
    } else {
      // Not needed so far; fail loudly rather than emit an alias that drops type parameters.
      fail(`generic type export ${name}<${typeParameters.join(', ')}> needs explicit support in scripts/build.mjs`);
    }
  }
  return lines.join('\n');
}

const NAMESPACE_DOC = `/**
 * The crypto-js 4.2.0 object (compat API), with cryptolite's modern API attached.
 * Types are reachable through it exactly as with @types/crypto-js, e.g. CryptoJS.lib.WordArray.
 */`;

function writeRootDeclarations({ compat, modern }) {
  const body = namespaceBody(compat, modern);
  write(
    path.join(DIST, 'index.d.ts'),
    `${GENERATED}import { CryptoJS as _C } from './types.js';
import * as _M from './modern.js';

${NAMESPACE_DOC}
declare namespace CryptoJS {
${body}
}
export default CryptoJS;

${compat.map((name) => `export import ${name} = _C.${name};`).join('\n')}

export * from './modern.js';
`,
  );
  write(
    path.join(DIST, 'index.d.cts'),
    `${GENERATED}import { CryptoJS as _C } from './types.cjs';
import * as _M from './modern.cjs';

${NAMESPACE_DOC}
declare namespace CryptoJS {
${body}
}
export = CryptoJS;
`,
  );
}

function writeShims() {
  for (const { name, path: prop } of SUBPATHS) {
    if (name === ROOT_ALIAS) continue;
    const member = prop === '' ? '' : `.${prop}`;
    const header = `${GENERATED}// crypto-js/${name} -> ${prop === '' ? 'the CryptoJS object' : `CryptoJS${member}`}\n`;
    if (prop === '') {
      write(path.join(DIST, `${name}.js`), `${header}export * from './index.js';\nexport { default } from './index.js';\n`);
      write(path.join(DIST, `${name}.d.ts`), `${header}export * from './index.js';\nexport { default } from './index.js';\n`);
    } else {
      write(
        path.join(DIST, `${name}.js`),
        `${header}import CryptoJS from './index.js';\nexport default CryptoJS${member};\n`,
      );
      write(
        path.join(DIST, `${name}.d.ts`),
        `${header}import CryptoJS from './index.js';\nexport default CryptoJS${member};\n`,
      );
    }
    write(path.join(DIST, `${name}.cjs`), `${header}module.exports = require('./index.cjs')${member};\n`);
    write(
      path.join(DIST, `${name}.d.cts`),
      `${header}import CryptoJS = require('./index.cjs');\nexport = CryptoJS${member};\n`,
    );
  }
}

function writeLegacyStubs() {
  for (const { name } of SUBPATHS) write(path.join(stubDir(name), 'package.json'), stubContent(name));
}

// ---------------------------------------------------------------------------------------------
// 5. package.json
// ---------------------------------------------------------------------------------------------
export function exportsMap() {
  const target = (stem) => ({
    import: { types: `./dist/${stem}.d.ts`, default: `./dist/${stem}.js` },
    require: { types: `./dist/${stem}.d.cts`, default: `./dist/${stem}.cjs` },
  });
  const map = { '.': target('index') };
  for (const { name } of SUBPATHS) {
    const stem = name === ROOT_ALIAS ? 'index' : name;
    map[`./${name}`] = target(stem);
    map[`./${name}.js`] = target(stem);
  }
  map['./package.json'] = './package.json';
  return map;
}

export function filesList() {
  return ['dist', ...SUBPATHS.map(({ name }) => name)];
}

function syncPackageJson() {
  const file = path.join(ROOT, 'package.json');
  const before = fs.readFileSync(file, 'utf8');
  const pkg = JSON.parse(before);
  pkg.exports = exportsMap();
  pkg.files = filesList();
  const after = `${JSON.stringify(pkg, null, 2)}\n`;
  if (after !== before) {
    fs.writeFileSync(file, after);
    log('package.json "exports"/"files" updated from scripts/subpaths.mjs');
  }
}

// ---------------------------------------------------------------------------------------------
// 6. type-check the shipped declarations
// ---------------------------------------------------------------------------------------------
function checkDeclarations() {
  const ts = require('@typescript/typescript6');
  const files = fs
    .readdirSync(DIST)
    .filter((f) => f.endsWith('.d.ts') || f.endsWith('.d.cts'))
    .map((f) => path.join(DIST, f));
  const program = ts.createProgram(files, {
    noEmit: true,
    strict: true,
    skipLibCheck: false,
    types: [],
    lib: ['lib.es2020.d.ts'],
    module: ts.ModuleKind.Node16,
    moduleResolution: ts.ModuleResolutionKind.Node16,
  });
  const diagnostics = ts.getPreEmitDiagnostics(program);
  if (diagnostics.length > 0) {
    const host = { getCanonicalFileName: (f) => f, getCurrentDirectory: () => ROOT, getNewLine: () => '\n' };
    fail(`generated declarations do not type-check:\n${ts.formatDiagnostics(diagnostics, host)}`);
  }
  return files.length;
}

async function main() {
  clean();
  buildJs();
  copyCompatTypes();
  await bundleModernTypes();
  const names = readExportNames();
  writeRootDeclarations(names);
  writeShims();
  writeLegacyStubs();
  syncPackageJson();
  const checked = checkDeclarations();
  log(
    `ok: ${SUBPATHS.length} subpaths, ${names.compat.length} compat + ${names.modern.length} modern exports, ` +
      `${checked} declaration files type-checked`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => fail(error?.stack ?? String(error)));
}
